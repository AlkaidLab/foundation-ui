// Extracts the Material Symbols (Rounded, weight 400) paths the UI uses into src/icons/icons.js.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../node_modules/@material-symbols/svg-400')
import { scanResult } from './scan-icons.mjs'
// the glyph set is the names listed by hand (src/icons/names.js) plus every name the code asks for (scripts/scan-icons.mjs), so a name used anywhere cannot be missing from the set
const listed = (await import('../src/icons/names.js')).NAMES
const scanned = scanResult()
if (scanned.unknown.length) { console.error('names that are not Material Symbols:', scanned.unknown.map((u) => `${u.name} (${u.files[0]})`).join(', ')); process.exit(1) }
const NAMES = [...new Set([...listed, ...scanned.names])]
const out = {}
const missing = []
for (const name of NAMES) {
  const read = (suffix) => {
    const file = path.join(root, 'rounded', `${name}${suffix}.svg`)
    return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
  }
  const line = read('')
  const fill = read('-fill')
  if (!line) { missing.push(name); continue }
  const d = (svg) => svg && [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ')
  out[name] = { d: d(line), ...(fill ? { f: d(fill) } : {}) }
}
if (missing.length) { console.error('missing icons:', missing.join(', ')); process.exit(1) }
const body = `// Generated by scripts/build-icons.mjs from Material Symbols (Rounded, 400, Apache-2.0). Do not edit.
// All glyphs are drawn on a 960-unit grid whose origin is at the bottom (viewBox "0 -960 960 960").
export const ICONS = ${JSON.stringify(out)}
`
fs.writeFileSync(path.join(here, '../src/icons/icons.js'), body)
console.log(Object.keys(out).length, 'icons,', body.length, 'bytes')
