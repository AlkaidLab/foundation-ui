// Generates src/css/shapes.css: the 35 shapes of the Material 3 Expressive shape library (scripts/material-shapes.mjs, ported from Compose Material3 MaterialShapes.kt)
// as polygons of SHAPE_POINTS points each, so clip-path interpolates between any two (a spring morph). `squircle` (a superellipse) and the kit's older names stay:
// cookie = cookie-9-sided, clover = clover-4-leaf; circle, sunny, burst and gem are the Material shapes of the same name.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { MATERIAL_SHAPES, shapeOutline, squircleOutline, samplePolygon, toClipPath } from './material-shapes.mjs'

export const SHAPE_POINTS = 96
export const SHAPE_ALIASES = { cookie: 'cookie-9-sided', clover: 'clover-4-leaf' }

export function shapePolygons(N = SHAPE_POINTS) {
  const out = {}
  for (const name of Object.keys(MATERIAL_SHAPES)) out[name] = samplePolygon(shapeOutline(name), N)
  for (const [alias, name] of Object.entries(SHAPE_ALIASES)) out[alias] = out[name]
  out.squircle = samplePolygon(squircleOutline(), N)
  return out
}

export function shapesCss() {
  const polys = shapePolygons()
  let css = `/* Generated by scripts/build-shapes.mjs; do not edit. The Material 3 Expressive shape library (MaterialShapes.kt), ${SHAPE_POINTS}-point polygons, so clip-path interpolates between any two. */\n:root {\n`
  for (const [name, poly] of Object.entries(polys)) css += `  --m-shape-${name}: ${toClipPath(poly)};\n`
  css += '}\n'
  for (const name of Object.keys(polys)) css += `.m-shape--${name} { clip-path: var(--m-shape-${name}); }\n`
  css += '.m-shape { transition: clip-path var(--m-spring-default-spatial-duration) var(--m-spring-default-spatial); }\n'
  return css
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = path.dirname(fileURLToPath(import.meta.url))
  const css = shapesCss()
  fs.writeFileSync(path.join(here, '../src/css/shapes.css'), css)
  console.log('shapes.css', css.length, 'bytes')
}
