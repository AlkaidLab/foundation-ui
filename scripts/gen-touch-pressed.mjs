// Generates src/css/touch-pressed.css: every top-level rule of src/css/*.css that has a `:active` state gets a twin with `[data-pressed]`
// (set by a11y/touchPress.js on the frame of a finger's or a pen's press; `:active` for a finger lags behind the press).
//   node scripts/gen-touch-pressed.mjs          writes the file
//   node scripts/gen-touch-pressed.mjs --check  exits 1 when the file is stale (test/touchpress.test.js runs it)
// The tray has its own pointer layer (src/tray/trayPointer.js, `data-pressed` on .m-tray children) and is left out.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'src/css')
const OUT = 'touch-pressed.css'
const SKIP = new Set([OUT, 'tray.css', 'all.css', 'testtools.css', 'installer.css'])

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '')

function splitTop(list) {
  const out = []
  let depth = 0, cur = ''
  for (const ch of list) {
    if (ch === '(' || ch === '[') depth++
    if (ch === ')' || ch === ']') depth--
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = '' } else cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

/** top-level `selectors { body }` rules; at-rules (media, keyframes, font-face) are skipped with their content */
export function topLevelRules(css) {
  const rules = []
  let depth = 0, head = '', body = ''
  for (const ch of stripComments(css)) {
    if (ch === '{') { if (depth === 0) body = ''; else body += ch; depth++; continue }
    if (ch === '}') {
      depth--
      if (depth === 0) { if (!head.trim().startsWith('@')) rules.push({ selector: head.trim(), body: body.trim() }); head = ''; body = '' } else body += ch
      continue
    }
    if (depth === 0) head += ch; else body += ch
  }
  return rules
}

export function build() {
  const blocks = []
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.css') && !SKIP.has(f)).sort()) {
    for (const rule of topLevelRules(fs.readFileSync(path.join(dir, file), 'utf8'))) {
      const twins = splitTop(rule.selector).filter((s) => s.includes(':active')).map((s) => s.replaceAll(':active', '[data-pressed]'))
      if (twins.length) blocks.push(`${twins.join(', ')} { ${rule.body.replace(/\s+/g, ' ')} }`)
    }
  }
  return `/* GENERATED by scripts/gen-touch-pressed.mjs from the \`:active\` rules of src/css/*.css: do not edit. Same rules, selected by \`[data-pressed]\`, which a11y/touchPress.js sets on the frame
   of a finger's or a pen's press (\`:active\` for touch starts after the browser's show-press delay). A mouse never sets it, so these rules need no media query. */
${blocks.join('\n')}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = build()
  const file = path.join(dir, OUT)
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
    if (now !== next) { console.error(`${OUT} is stale: run node scripts/gen-touch-pressed.mjs`); process.exit(1) }
  } else { fs.writeFileSync(file, next); console.log(`${OUT}: ${next.split('\n').length - 3} rules`) }
}
