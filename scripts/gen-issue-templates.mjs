// Writes src/devmode/issueTemplates.js from the ISSUE_TEMPLATE files of a repository checkout or download:
//   node scripts/gen-issue-templates.mjs <repo id> <dir with the .yml files> > src/devmode/issueTemplates.js   (several: <id>=<dir> pairs)
// The built-in copy is what the report composer writes its body from (offline, in the order of the fields) and what the reader of an issue falls back to when the live templates cannot be read.
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseTemplate } from '../src/devmode/issueForm.js'

const pairs = process.argv.slice(2).map((a) => a.split('='))
const out = {}
for (const [id, dir] of pairs) {
  out[id] = readdirSync(dir).filter((f) => /\.ya?ml$/.test(f) && f !== 'config.yml').sort().map((f) => parseTemplate(f, readFileSync(join(dir, f), 'utf8'))).filter(Boolean)
}
process.stdout.write(`// GENERATED by scripts/gen-issue-templates.mjs from .github/ISSUE_TEMPLATE of the repository (${new Date().toISOString().slice(0, 10)}); do not edit by hand.\n// The Issue Forms of each repository the developer page knows, as parseTemplate reads them.\nexport const BUILTIN_TEMPLATES = ${JSON.stringify(out, null, 1)}\n`)
