/** The partial table for a code and a module. English and Chinese have none (they are the bases). */
export const partialFor = (locale, moduleName) => {
  const code = canonicalLocale(locale)
  if (code === 'en' || code === 'zh') return null
  return PARTIALS[code]?.[moduleName] || null
}

/** Resolve one module: en and zh are its full tables, locale selects the partial. */
export const textTable = (moduleName, locale, en, zh) => resolveTexts(en, zh, locale, partialFor(locale, moduleName))
